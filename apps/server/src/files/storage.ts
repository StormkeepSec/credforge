import { randomBytes } from 'node:crypto';
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, join, sep } from 'node:path';
import {
  DeleteObjectCommand,
  GetObjectCommand,
  PutObjectCommand,
  S3Client,
} from '@aws-sdk/client-s3';
import type { StorageConfig } from '../config';

/**
 * Where uploaded files live (design plan §13.5): a local directory for self-hosters and offline
 * development, or an S3-compatible bucket (DigitalOcean Spaces on credforge.app). Buckets stay
 * private; public images are served through the app at permanent credforge URLs, never at
 * storage URLs, so the provider can change without breaking issued credentials.
 */
export interface Storage {
  readonly driver: 'local' | 's3';
  /** The bucket for `s3`; null for `local`. */
  readonly bucket: string | null;
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  /** The object's bytes, or null if there is none. */
  get(key: string): Promise<Buffer | null>;
  delete(key: string): Promise<void>;
}

export class StorageKeyError extends Error {
  constructor(key: string) {
    super(`Invalid storage key: ${JSON.stringify(key)}`);
    this.name = 'StorageKeyError';
  }
}

const KEY = /^[A-Za-z0-9][A-Za-z0-9._-]*(?:\/[A-Za-z0-9][A-Za-z0-9._-]*)*$/;

/** Keys are generated by credforge; anything else (`..`, empty segments, odd characters) is a bug. */
export function assertStorageKey(key: string): void {
  if (key.length > 512 || !KEY.test(key) || key.split('/').some((part) => part === '..')) {
    throw new StorageKeyError(key);
  }
}

export function createStorage(config: StorageConfig): Storage {
  return config.driver === 's3' ? createS3Storage(config) : createLocalStorage(config.localDir);
}

/** Files under a directory, one file per key (`orgs/{orgId}/…` becomes subdirectories). */
export function createLocalStorage(root: string): Storage {
  const pathOf = (key: string) => {
    assertStorageKey(key);
    return join(root, ...key.split('/'));
  };
  return {
    driver: 'local',
    bucket: null,
    async put(key, body) {
      const path = pathOf(key);
      await mkdir(dirname(path), { recursive: true });
      // Write then rename, so a reader never sees a half-written file.
      const temporary = `${path}.${randomBytes(6).toString('hex')}.tmp`;
      await writeFile(temporary, body);
      await rename(temporary, path);
    },
    async get(key) {
      try {
        return await readFile(pathOf(key));
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null;
        throw error;
      }
    },
    async delete(key) {
      await rm(pathOf(key), { force: true });
    },
  };
}

type S3Config = Extract<StorageConfig, { driver: 's3' }>;

/** The parts of the AWS SDK client the driver uses, so tests can stand in for it. */
export type S3Sender = Pick<S3Client, 'send'>;

/**
 * Any S3-compatible bucket through the AWS SDK v3. Objects are written without an ACL, so they
 * keep the bucket's private default.
 */
export function createS3Storage(config: S3Config, client?: S3Sender): Storage {
  const s3 =
    client ??
    new S3Client({
      endpoint: config.endpoint,
      region: config.region,
      forcePathStyle: config.forcePathStyle,
      credentials: {
        accessKeyId: config.accessKeyId,
        secretAccessKey: config.secretAccessKey,
      },
      // The SDK's default CRC32 checksums aren't supported by every S3-compatible service.
      requestChecksumCalculation: 'WHEN_REQUIRED',
      responseChecksumValidation: 'WHEN_REQUIRED',
    });
  const Bucket = config.bucket;
  return {
    driver: 's3',
    bucket: Bucket,
    async put(key, body, contentType) {
      assertStorageKey(key);
      await s3.send(
        new PutObjectCommand({ Bucket, Key: key, Body: body, ContentType: contentType }),
      );
    },
    async get(key) {
      assertStorageKey(key);
      try {
        const response = await s3.send(new GetObjectCommand({ Bucket, Key: key }));
        if (!response.Body) return null;
        return Buffer.from(await response.Body.transformToByteArray());
      } catch (error) {
        if (isNotFound(error)) return null;
        throw error;
      }
    },
    async delete(key) {
      assertStorageKey(key);
      await s3.send(new DeleteObjectCommand({ Bucket, Key: key }));
    },
  };
}

function isNotFound(error: unknown): boolean {
  const e = error as { name?: string; $metadata?: { httpStatusCode?: number } };
  return e?.name === 'NoSuchKey' || e?.name === 'NotFound' || e?.$metadata?.httpStatusCode === 404;
}

/** For log messages: where files go, without credentials. */
export function describeStorage(config: StorageConfig): string {
  return config.driver === 's3'
    ? `s3 bucket ${config.bucket}${config.endpoint ? ` at ${config.endpoint}` : ''}`
    : `local directory ${config.localDir.split(sep).join('/')}`;
}
