// Builds a complete, signed sample for checking credforge's output with external tools such as the
// 1EdTech Open Badges validator. Everything is deterministic: a fixed test key, fixed ids and dates.

import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import {
  Bitstring,
  bakePng,
  bakeSvg,
  buildIssuerProfile,
  buildStatusListEntry,
  type CredentialInput,
  createEd25519Signer,
  generateEd25519KeyPair,
  type IssuerInput,
  issueCredential,
  issueStatusListCredential,
} from '../src/index';

export const DEFAULT_SAMPLE_BASE_URL = 'https://credforge.app/ob3-sample';

const ISSUER_UUID = '5a1e0c7d-3b2f-4e8a-9c6d-0f1e2d3c4b5a';
const ACHIEVEMENT_UUID = '8b7c6d5e-4f3a-4b2c-8d1e-0a9b8c7d6e5f';
const ISSUED_AT = '2026-10-01T09:00:00Z';
const ACTIVE_INDEX = 31_337;
const REVOKED_INDEX = 90_210;

/** The key is derived from a public string: it is for this sample only and protects nothing. */
const SAMPLE_KEY_SEED = 'credforge ob3 sample issuer key (public, test only)';

const brand = (file: string) =>
  readFileSync(new URL(`../../../apps/web/public/brand/${file}`, import.meta.url));

/**
 * Returns the sample files by relative path. Files under `public/` must be served at `baseUrl`
 * (with `Content-Type: application/json` for the extensionless JSON documents) before a validator
 * that dereferences URLs can check the credentials that carry a status entry.
 */
export async function buildSampleFixtures(
  baseUrl = DEFAULT_SAMPLE_BASE_URL,
): Promise<Map<string, string | Uint8Array>> {
  const base = baseUrl.replace(/\/+$/, '');
  const issuerId = `${base}/issuers/${ISSUER_UUID}`;
  const statusListId = `${base}/status/${ISSUER_UUID}/1`;

  const keyPair = await generateEd25519KeyPair(
    createHash('sha256').update(SAMPLE_KEY_SEED).digest(),
  );
  const issuer: IssuerInput = {
    id: issuerId,
    name: 'credforge sample issuer (test only)',
    url: new URL(base).origin,
    description: 'A sample issuer for checking credforge output with external validators.',
    image: `${base}/images/issuer.png`,
  };
  const signer = await createEd25519Signer({ controller: issuerId, ...keyPair });
  const issuerProfile = buildIssuerProfile({ ...issuer, keys: [keyPair] });
  const options = { signer, issuerProfile, created: ISSUED_AT };

  const input = (name: string, uuid: string, index?: number): CredentialInput => ({
    id: `${base}/credentials/${uuid}`,
    issuer,
    achievement: {
      id: `${base}/achievements/${ACHIEVEMENT_UUID}`,
      name: 'Sample Badge',
      description: 'A sample achievement used to check credforge credentials with validators.',
      criteria: { narrative: 'Generated by `pnpm --filter @credforge/ob3 fixtures`.' },
      image: `${base}/images/badge.png`,
      tag: ['sample'],
    },
    recipient: { email: 'sample.recipient@example.com', salt: 'credforge-sample', name },
    validFrom: ISSUED_AT,
    evidence: [{ name: 'Sample evidence', narrative: 'Evidence is optional.' }],
    credentialStatus:
      index === undefined
        ? undefined
        : buildStatusListEntry({ statusListCredential: statusListId, index }),
  });

  const credential = await issueCredential(
    input('Sam Sample', 'c0ffee00-1234-4abc-8def-0123456789ab', ACTIVE_INDEX),
    options,
  );
  const revoked = await issueCredential(
    input('Rae Revoked', 'c0ffee00-1234-4abc-8def-0123456789ac', REVOKED_INDEX),
    options,
  );
  const noStatus = await issueCredential(
    input('Noa Nostatus', 'c0ffee00-1234-4abc-8def-0123456789ad'),
    options,
  );

  const bitstring = new Bitstring();
  bitstring.set(REVOKED_INDEX, true);
  const statusList = await issueStatusListCredential(
    { id: statusListId, issuer: issuerId, bitstring, validFrom: ISSUED_AT },
    options,
  );

  const json = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;
  const badgePng = brand('credforge-mark.png');
  const badgeSvg = brand('credforge-mark.svg').toString('utf8');
  return new Map<string, string | Uint8Array>([
    ['credential.json', json(credential)],
    ['credential-revoked.json', json(revoked)],
    ['credential-no-status.json', json(noStatus)],
    ['badge.png', bakePng(badgePng, credential)],
    ['badge-no-status.png', bakePng(badgePng, noStatus)],
    ['badge.svg', bakeSvg(badgeSvg, credential)],
    [`public/issuers/${ISSUER_UUID}`, json(issuerProfile)],
    [`public/status/${ISSUER_UUID}/1`, json(statusList)],
    ['public/images/issuer.png', badgePng],
    ['public/images/badge.png', badgePng],
  ]);
}
